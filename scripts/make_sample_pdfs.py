def make_pdf(title: str, html: str, path: Path):
    doc = pymupdf.open()
    page = doc.new_page()
    page.insert_htmlbox(pymupdf.Rect(60, 50, 540, 800), html, css="* {font-size: 12pt;}")
    doc.set_metadata({"title": title})
    doc.save(path)
    return doc


def make_scan(src: Path, path: Path):
    """Растеризует PDF в картинку — получается «скан» без текстового слоя (проверка OCR)."""
    with pymupdf.open(src) as doc:
        out = pymupdf.open()
        for page in doc:
            pix = page.get_pixmap(dpi=200, colorspace=pymupdf.csGRAY)
            p = out.new_page(width=page.rect.width, height=page.rect.height)
            p.insert_image(p.rect, pixmap=pix)
        out.save(path)


